#!/usr/bin/env python3
"""Compile the Book of Names designs (design/*.yaml) into natural-capital-2/tracks.yaml.

    python3 natural-capital-2/build.py      # writes tracks.yaml, prints warnings, exits 1 if any

tracks.yaml has the same shape as docs/album/tracks.yaml, so the Kaggle notebook (kaggle/plan.py) and the
laptop loop render it unchanged. Voice notes (status: voice) are listed with their script but no caption,
so plan.py skips them. Checks the band's caption rules (Nov 14): no static-prone words, nothing circus-like,
no clean/polished mix, songs start straight in and end sung, <= 260 s. Needs only PyYAML.
"""
import glob
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))

AVOID = [
    # static and hiss
    "crackle", "crackling", "hiss", "static", "vinyl", "gramophone", "typewriter", "lo-fi", "raw mix", "tape",
    # circus and oom-pah
    "circus", "oom-pah", "oompah", "tuba", "pizzicato", "woodblock", "marching", "march", "comic", "comedic",
    "theatrical", "playful", "cheeky", "whimsical", "kazoo", "slide whistle",
    # mixes that make instruments stick out
    "clean polished", "polished", "clean mix",
]
AVOID_RE = re.compile(r"\b(" + "|".join(re.escape(w) for w in AVOID) + r")\b", re.I)
SPOKEN_RE = re.compile(r"\b(spoken|speech|narrat|voiceover)", re.I)


class Literal(str):
    pass


yaml.add_representer(Literal, lambda d, s: d.represent_scalar("tag:yaml.org,2002:str", s, style="|"))


def build():
    tracks, problems = [], []
    for path in sorted(glob.glob(os.path.join(HERE, "design", "*.yaml"))):
        d = yaml.safe_load(open(path))
        name, r = d["slug"], d["render"]
        t = {"n": d["order"], "slug": name, "title": d["title"], "credit": d.get("credit", ""),
             "status": d.get("status", "generate"), "seconds": r["seconds"]}
        if t["status"] == "voice":
            t["script"] = Literal(d["script"].strip() + "\n")
            tracks.append(t)
            continue

        caption = " ".join(d["caption"].split())
        lyrics = d["lyrics"].strip() + "\n"
        for m in AVOID_RE.finditer(caption):
            problems.append(f"{name}: caption has banned word '{m.group(0)}'")
        if SPOKEN_RE.search(caption):
            problems.append(f"{name}: caption asks for speech; songs are sung or rapped")
        if len(caption) > 1000:
            problems.append(f"{name}: caption is {len(caption)} chars; keep it under ~1000")
        if r["seconds"] > 260:
            problems.append(f"{name}: {r['seconds']} s is over the 260 s limit")
        for tag in re.findall(r"\[([^\]]*)\]", lyrics):
            if AVOID_RE.search(tag):
                problems.append(f"{name}: tag [{tag}] has a banned word")
            if len(tag.split()) > 16:
                problems.append(f"{name}: tag [{tag}] is over 16 words")
        tags = re.findall(r"\[([^\]]*)\]", lyrics)
        if "immediately" not in tags[0] and "straight" not in tags[0]:
            problems.append(f"{name}: first section should start straight in (no instrumental intro)")
        if SPOKEN_RE.search(tags[-1]) or "sung" not in tags[-1] and "chorus" not in tags[-1]:
            problems.append(f"{name}: last section [{tags[-1]}] must be sung")
        for line in lyrics.splitlines():
            if re.fullmatch(r"\s*\(.*\)\s*", line):
                problems.append(f"{name}: '{line.strip()}' is all in brackets and gets stripped")

        t.update({"bpm": r["bpm"], "key": r["key"], "timesig": str(r["timesig"]),
                  "caption": caption, "lyrics": Literal(lyrics)})
        tracks.append(t)

    tracks.sort(key=lambda t: t["n"])
    doc = yaml.safe_load(open(os.path.join(HERE, "queue.yaml")))
    known = {t["slug"] for t in tracks if t["status"] == "generate"}
    for s in set(doc["queue"]) ^ known:
        problems.append(f"queue.yaml and the designs disagree about '{s}'")
    doc["tracks"] = tracks
    out = os.path.join(HERE, "tracks.yaml")
    with open(out, "w") as f:
        f.write("# GENERATED by natural-capital-2/build.py from design/*.yaml and queue.yaml. Edit those, not this.\n")
        yaml.dump(doc, f, sort_keys=False, allow_unicode=True, width=110)
    return out, tracks, problems


if __name__ == "__main__":
    out, tracks, problems = build()
    total = 0
    for t in tracks:
        total += t["seconds"]
        extra = f"{t['bpm']:>3} bpm  {t['key']:<9}" if t["status"] == "generate" else "voice note        "
        print(f"{t['n']:>2} {t['slug']:<24} {extra} {t['seconds']:>3} s")
    print(f"{len(tracks)} tracks, {total // 60}:{total % 60:02d} total; wrote {out}")
    for p in problems:
        print("WARNING:", p)
    sys.exit(1 if problems else 0)
